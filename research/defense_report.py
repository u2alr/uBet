"""Writes research/RESULTS_DEFENSE.md and shared/defense.status.json from research/out/def_dev.json (and def_final.json if fold F was used).
Every number is copied by script from the JSON: nothing is typed by hand.

    python research/defense_report.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
STATUS = HERE.parent / "shared" / "defense.status.json"
STATS = ["pts", "reb", "ast", "fg3m", "pra"]
RULE = ["pts", "reb", "ast", "fg3m"]
GROUPS = ["TD", "PD", "MU"]
NAMES = {"TD": "team defence (B)", "PD": "individual defenders (C)", "MU": "likely matchup (D)"}


def cell(r):
    return f"{r['dlogscore']:+.4f} [{r['ci_lo']:+.4f}, {r['ci_hi']:+.4f}]"


def main():
    d = json.loads((OUT / "def_dev.json").read_text())
    final = json.loads((OUT / "def_final.json").read_text()) if (OUT / "def_final.json").exists() else None
    variants = [k for k in d["A"]["stats"]["pts"] if isinstance(d["A"]["stats"]["pts"][k], dict) and "dlogscore" in d["A"]["stats"]["pts"][k]]
    L = ["# Results: Defensive Matchup Engine ablation (PREREG_DEFENSE.md)", "",
         "Generated by `python research/defense_report.py` from `research/out/def_dev.json` (and `def_final.json` if the final season was used). Paired difference in per-row negative-binomial log score against the baseline (the production feature set); positive = better; 95% bootstrap interval resampling calendar weeks; rotation players (last-10 minutes 20+); the same rows for every variant.", ""]
    for f in ("A", "B"):
        L += [f"## Fold {f}: test season {d[f]['season']} ({d[f]['n_test']:,} rows)", "", "| variant | " + " | ".join(STATS) + " |", "|---|" + "---|" * len(STATS)]
        for v in variants:
            L.append(f"| {v} | " + " | ".join(cell(d[f]['stats'][s][v]) for s in STATS) + " |")
        L.append("")
    for f in ("A", "B"):
        b = d[f]["stats"]["pts"]
        L += [f"## Pseudo-line probability quality, fold {f}, points (baseline vs each variant)", "", "| variant | Brier | log loss | calibration slope | MAE |", "|---|---|---|---|---|",
              f"| baseline | {b['baseline']['brier_pseudo']:.4f} | {b['baseline']['logloss_pseudo']:.4f} | {b['baseline']['cal_slope']:.3f} | {b['baseline']['mae']:.3f} |"]
        for v in variants:
            L.append(f"| {v} | {b[v]['brier_pseudo']:.4f} | {b[v]['logloss_pseudo']:.4f} | {b[v]['cal_slope']:.3f} | {b[v]['mae']:.3f} |")
        L.append("")
    L += ["Pseudo-lines are the nearest half-integer to the last-10 average, NOT sportsbook lines.", ""]
    for g in GROUPS:
        for bucket in d["B"]["stats"]["pts"][g]["buckets"]:
            L += [f"## {NAMES[g]} by {bucket} (fold B; descriptive only, never used to decide)", "", "| bucket | " + " | ".join(RULE) + " |", "|---|" + "---|" * len(RULE)]
            for lab in d["B"]["stats"]["pts"][g]["buckets"][bucket]:
                row = []
                for s in RULE:
                    x = d["B"]["stats"][s][g]["buckets"][bucket][lab]
                    row.append(f"{x['dlogscore']:+.4f} [{x['ci_lo']:+.4f}, {x['ci_hi']:+.4f}] n={x['n']:,}" if "dlogscore" in x else f"n={x['n']:,} (too few)")
                L.append(f"| {lab} | " + " | ".join(row) + " |")
            L.append("")
    L += ["## Feature coverage on the test rows (share not missing)", "", "| feature | fold A | fold B |", "|---|---|---|"]
    for k in d["A"]["coverage"]:
        L.append(f"| {k} | {d['A']['coverage'][k]:.0%} | {d['B']['coverage'][k]:.0%} |")
    L += ["", "## Does a feature explain what the baseline misses? (Spearman with the baseline's standardised residual, fold B, points)", "", "| feature | rho | n |", "|---|---|---|"]
    for k, v in d["B"]["stats"]["pts"]["partial_association"].items():
        L.append(f"| {k} | {'' if v['rho_with_baseline_residual'] is None else format(v['rho_with_baseline_residual'], '+.3f')} | {v['n']:,} |")
    L += ["", "## Overlap with existing features (largest absolute Spearman correlation with any of the 68 baseline features)", "", "| feature | max abs rho | with |", "|---|---|---|"]
    for k, v in d["overlap_with_existing_features"].items():
        L.append(f"| {k} | {v['max_abs_spearman_with_existing']:.2f} | {v['existing_feature']} |")
    verdict = d["verdict_dev"]
    L += ["", "## Verdict by the rule fixed in advance", ""]
    for g, ok in verdict.items():
        L.append(f"- **{g}** ({NAMES[g]}): {'passed the development folds' if ok else 'DROPPED (did not pass on both folds)'}")
    kept = [g for g, ok in verdict.items() if ok]
    if final:
        L += ["", f"Final season used once for {kept}: confirmed on F: {final['groups_confirmed_on_F']}."]
    else:
        L += ["", "Fold F (the final season) was **not used**: no group passed development, so there was nothing to confirm."] if not kept else ["", "Fold F has not been used yet."]
    L += ["", "## What this means",
          "- A group qualifies only if at least 3 of 4 statistics have an interval above 0 on BOTH folds and none below. The table has many comparisons; isolated intervals above 0 are expected by chance.",
          "- Nothing here involves a sportsbook price. Better accuracy against a naive baseline is not an edge over the market.",
          "- Assignments are estimated from history (not confirmed), switches are not recorded in the feed, late absences are unknown historically, and shot-zone, rim-protection and play-type defence exist only as end-of-season snapshots, so they could not be used without leaking."]
    (HERE / "RESULTS_DEFENSE.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    confirmed = final["groups_confirmed_on_F"] if final else []
    status = {"version": "def-v1", "evaluated": True, "adjustsPredictions": False, "groupsKept": confirmed,
              "summary": ("None of the team-defence, individual-defender or likely-matchup features improved out-of-sample accuracy reliably enough to pass the pre-registered rule, so none of them changes any prediction. The defensive context is shown for information only."
                          if not kept else (
                              f"Team-level defensive features ({', '.join(confirmed or kept)}) improved out-of-sample accuracy on both development seasons"
                              + (" and held on the final season" if confirmed else "")
                              + ", with small gains. They are research-only: they are not calibrated for production or approved, so they do not change any prediction yet. "
                              "The individual-defender and likely-matchup features did not pass, so the matchup context shown is descriptive."
                              if confirmed else f"Groups passing development: {', '.join(kept)}; the final season has not confirmed them yet, and they do not change any prediction.")),
              "evidence": "research/RESULTS_DEFENSE.md"}
    STATUS.write_text(json.dumps(status, indent=2) + "\n", encoding="utf-8")
    print("wrote RESULTS_DEFENSE.md and defense.status.json; kept groups:", kept)


if __name__ == "__main__":
    main()
