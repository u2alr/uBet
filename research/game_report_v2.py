"""Turns research/out/games_v2h.json (from game_eval_v2.py) into research/RESULTS_GAMES_V2.md and shared/games.status.json. Numbers only: nothing is re-fitted here.

    ingest/.venv/Scripts/python research/game_report_v2.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
res = json.loads((HERE / "out" / "games_v2h.json").read_text())
folds, rule = res["folds"], res["rule"]
NAMES = {"elo": "Elo only", "v1": "games-v1 (Elo + availability)", "lin_v2": "lin_v2 (the new model)", "gbm_v2": "gbm_v2 (boosted trees)", "blend": "blend of lin_v2 and gbm_v2",
         "v1+srs": "v1 + opponent-adjusted ratings", "v1+talent": "v1 + talent-weighted availability", "v1+commonopp": "v1 + common opponents", "v1+schedule": "v1 + rest and back-to-backs"}
LABEL = {"E0": "2022-23 (train 2018-22)", "A": "2023-24 (train 2018-23)", "B": "2024-25 (train 2018-24)", "F": "2025-26 (train 2018-25; confirmation)", "new": "2026-27 so far (train 2018-26)"}


def table(fold: str) -> str:
    f = folds[fold]
    rows = ["| Model | Log loss | vs v1 (paired, 95%) | Brier | Accuracy | Calibration slope |", "|---|---|---|---|---|---|"]
    for k, m in f["models"].items():
        d = "reference" if k == "v1" else f"{m['dlogloss_vs_v1']:+.4f} [{m['ci_lo']:+.4f}, {m['ci_hi']:+.4f}]"
        rows.append(f"| {NAMES.get(k, k)} | {m['logloss']:.4f} | {d} | {m['brier']:.4f} | {m['accuracy']:.1%} | {m['cal_slope']:.2f} |")
    return f"### {LABEL[fold]} ({f['n_test']:,} games)\n\n" + "\n".join(rows) + "\n"


md = f"""# Results: game-winner model v2 (PREREG_GAMES_V2.md)

Generated by `research/game_report_v2.py` from `research/out/games_v2h.json`. Lower log loss is better; "vs v1" is v1's loss minus the model's, so positive means better than v1.

## Decision under the pre-registered rule

- Candidate: **{rule['candidate']}** (lowest mean development log loss over E0, A and B).
- Pooled paired improvement over v1 on E0 + A + B: **{rule['pooled_dlogloss_vs_v1']:+.4f}**, 95% interval [{rule['ci_lo']:+.4f}, {rule['ci_hi']:+.4f}] (must be entirely above 0: {'yes' if rule['a_ci_above_zero'] else 'no'}).
- On F, log loss not worse than v1's by more than 0.001: {'yes' if rule['b_F_not_worse_by_0.001'] else 'no'}. Calibration slope on F within 0.9 to 1.1: {'yes' if rule['c_F_slope_ok'] else 'no'}.
- **Adopted: {'yes' if rule['adopt_v2'] else 'no'}.**

## What this does and does not show

- The gain is in the probabilities (log loss, Brier), not in picking more winners: accuracy is about the same as v1's.
- Extra model complexity did not help: the boosted model never beat the linear one, even with eight seasons of training data.
- Folds A, B and F were seen in earlier experiments, so only the live stream (`game_lean_log`, which stores both models' numbers before every game) is a clean test.
- Nothing here is a test against sportsbook prices: no historical game lines exist.

## Folds

""" + "\n".join(table(f) for f in ("E0", "A", "B", "F", "new") if f in folds)
(HERE / "RESULTS_GAMES_V2.md").write_text(md, encoding="utf-8")

F = folds["F"]["models"]
status = {
    "version": "games-v2" if rule["adopt_v2"] else "games-v1",
    "evaluated": True,
    "model": "elo+ratings+talent+rest (logistic)" if rule["adopt_v2"] else "baseline+AVAIL3",
    "groupsKept": ["ELO", "ADJUSTED_RATINGS", "TALENT_AVAILABILITY", "REST"] if rule["adopt_v2"] else ["AVAIL3"],
    "logLoss": round(F[rule["candidate"] if rule["adopt_v2"] else "v1"]["logloss"], 4),
    "brier": round(F[rule["candidate"] if rule["adopt_v2"] else "v1"]["brier"], 4),
    "calibrationSlope": round(F[rule["candidate"] if rule["adopt_v2"] else "v1"]["cal_slope"], 3),
    "accuracy": round(F[rule["candidate"] if rule["adopt_v2"] else "v1"]["accuracy"], 3),
    "testGames": folds["F"]["n_test"],
    "testSeason": "2025-26",
    "baselineLogLoss": round(F["v1"]["logloss"], 4),
    "baselineName": "games-v1 (Elo + availability)",
    "pooledImprovementOverV1": {"dlogloss": round(rule["pooled_dlogloss_vs_v1"], 4), "ciLo": round(rule["ci_lo"], 4), "ciHi": round(rule["ci_hi"], 4)},
    "summary": ("Home advantage, a margin-aware Elo, ratings adjusted for the strength of every opponent (so results like 'A beat C, B lost to C' are used together), "
                "the talent of any rotation player the injury report lists as Out, and rest. It was tested with the players who actually sat out, "
                "so that is a best case: late scratches, Questionable players and lineup news are not seen. Its advantage over the earlier model is in the probabilities, not in more correct picks. "
                "It has not been tested against sportsbook lines."),
    "evidence": "research/RESULTS_GAMES_V2.md",
}
(HERE.parent / "shared" / "games.status.json").write_text(json.dumps(status, indent=1) + "\n", encoding="utf-8")
print("wrote RESULTS_GAMES_V2.md and shared/games.status.json (version", status["version"] + ")")
