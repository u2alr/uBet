"""Fit the negative-binomial dispersion tables behind the opt-in 'baseline-v3' fallback model.

    ingest/.venv/Scripts/python research/fit_dispersion.py

Writes shared/dispersion.json, the single source of truth read by BOTH shared/baseline.ts and the Python tests.

`policy` is not tuned here. It encodes the outcome of the pre-registered rule in PREREG_AUDIT.md as applied by
research/dist_study.py on the development folds: a distribution replaces the app's native Poisson/normal rule for a
(statistic, mean-bucket) cell only if it beat it with a 95% interval above 0 in BOTH folds on at least 400 rows;
where several qualified, the one with the best mean log score across the folds was taken (this tie-break was chosen
after seeing the results, which is a small deviation from the pre-registration and is recorded in AUDIT.md).
The dispersion values themselves are fitted on all seasons through 2025-26.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from models import Dispersion, app_stats  # noqa: E402

OUT = Path(__file__).resolve().parent / "out"
SHARED = Path(__file__).resolve().parents[1] / "shared" / "dispersion.json"
STATS6 = ["pts", "reb", "ast", "fg3m", "stl", "blk"]

# kind per mean bucket: lt2 = mean < 2, mid = 2 <= mean < 6, hi = mean >= 6
#   native = keep the app's rule (Poisson below 6, normal above)   nb = negative binomial, dispersion depends on the mean
#   nbc    = negative binomial with one constant dispersion per statistic
POLICY = {
    "pts":  {"lt2": "nb",  "mid": "nb",     "hi": "native"},
    "reb":  {"lt2": "nb",  "mid": "nb",     "hi": "nb"},
    "ast":  {"lt2": "nbc", "mid": "nb",     "hi": "nb"},
    "fg3m": {"lt2": "nbc", "mid": "nb",     "hi": "native"},
    "stl":  {"lt2": "nbc", "mid": "native", "hi": "native"},
    "blk":  {"lt2": "nbc", "mid": "native", "hi": "native"},
}


def main():
    df = pd.read_pickle(OUT / "features.pkl").sort_values(["PLAYER_ID", "date", "GAME_ID"]).reset_index(drop=True)
    df["stl"], df["blk"] = df["STL"], df["BLK"]
    ok = (df.n_prior >= 5) & df["pts_l10"].notna()
    table, n_rows = {}, int(ok.sum())
    for s in STATS6:
        a = app_stats(df, s).loc[ok]
        mu, y = a["mean"].to_numpy(float), df.loc[ok, s].to_numpy(float)
        keep = np.isfinite(mu)
        mu, y = mu[keep], y[keep]
        d = Dispersion().fit(mu, y)
        const = max(float((((y - mu) ** 2 - mu).sum()) / (mu ** 2).sum()), 1e-3)
        table[s] = {"centers": [round(float(c), 6) for c in d.c], "alphas": [round(float(x), 6) for x in d.a], "constant": round(const, 6)}
        print(f"{s:<5} alpha(mean): " + ", ".join(f"{c:.2f}->{x:.3f}" for c, x in zip(d.c, d.a)) + f"   constant {const:.3f}")
    SHARED.write_text(json.dumps({
        "note": "Generated by research/fit_dispersion.py. Policy comes from PREREG_AUDIT.md / dist_study.py; do not edit by hand.",
        "fittedOn": f"{n_rows} eligible player-games, seasons 2022-23 to 2025-26",
        "policy": POLICY, "dispersion": table,
    }, indent=1))
    print(f"wrote {SHARED}")


if __name__ == "__main__":
    main()
