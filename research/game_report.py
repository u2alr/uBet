"""Writes research/RESULTS_GAMES.md and shared/games.status.json from research/out/games_dev.json (and games_final.json if fold F was used).
Every number is copied by script from the JSON: nothing is typed by hand.

    python research/game_report.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
STATUS = HERE.parent / "shared" / "games.status.json"


def main():
    d = json.loads((OUT / "games_dev.json").read_text())
    final = json.loads((OUT / "games_final.json").read_text()) if (OUT / "games_final.json").exists() else None
    L = ["# Results: game-winner view (PREREG_GAMES.md)", "",
         "Generated by `python research/game_report.py` from `research/out/games_dev.json` (and `games_final.json` if the final season was used). Regular-season games only. dlogloss is the paired per-game log-loss improvement over the baseline (home advantage + Elo); positive = better; 95% bootstrap interval resampling calendar weeks.", ""]
    for f in ("A", "B"):
        r = d[f]
        b = r["baseline"]
        L += [f"## Fold {f}: test season {r['season']} ({r['n_test']:,} games)", "",
              f"Baseline (home advantage + Elo): log loss {b['logloss']:.4f}, Brier {b['brier']:.4f}, calibration slope {b['cal_slope']:.3f}, accuracy {b['accuracy']:.1%}. A coin flip has log loss 0.6931.", "",
              "| variant | dlogloss [95% interval] | log loss | Brier | calibration slope | accuracy | picks that differ from baseline (model right) |", "|---|---|---|---|---|---|---|"]
        for v, x in r["variants"].items():
            diff = f"{x['picks_differ_from_baseline']} ({x['model_right_when_differ']:.0%})" if x.get("model_right_when_differ") is not None else "0"
            L.append(f"| {v} | {x['dlogloss']:+.5f} [{x['ci_lo']:+.5f}, {x['ci_hi']:+.5f}] | {x['logloss']:.4f} | {x['brier']:.4f} | {x['cal_slope']:.3f} | {x['accuracy']:.1%} | {diff} |")
        L.append("")
    allv = d["B"]["variants"]["ALL (information only)"]
    L += ["## Calibration by predicted-probability band (fold B, all groups, descriptive)", "", "| band | games | predicted | actual |", "|---|---|---|---|"]
    for band, x in allv["by_band"].items():
        L.append(f"| {band} | {x['n']:,} | {x['predicted']:.1%} | {x['actual']:.1%} |")
    L += ["", "## Verdict by the rule fixed in advance", ""]
    verdict = d["verdict_dev"]
    for g, ok in verdict.items():
        L.append(f"- **{g}**: {'passed both development folds' if ok else 'not kept (interval did not clear 0 on both folds)'}")
    kept = [g for g, ok in verdict.items() if ok]
    L += ["", ("Fold F (the final season) was **not used**: no group passed development, so the displayed model view is the baseline (home advantage + Elo)." if not kept
               else f"Fold F used once for {kept}: confirmed {final['groups_confirmed_on_F'] if final else 'pending'}."), "",
          "## What this means",
          "- The displayed view is the plain rating baseline unless a group passed. Its log loss is far below a coin flip, but it is a rating model: it cannot see injuries or lineups.",
          "- No sportsbook line exists historically here, so nothing in this file says the model beats the market. Markets are usually more accurate than a simple rating model; a gap between the two is more likely the model's blind spot than an opportunity.",
          "- Forward comparison starts now: every snapshot stores the model's and the market's chance side by side (`game_lean_log`)."]
    (HERE / "RESULTS_GAMES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    b = d["B"]["baseline"]
    confirmed = final["groups_confirmed_on_F"] if final else []
    STATUS.write_text(json.dumps({
        "version": "games-v1", "evaluated": True, "model": "baseline" if not confirmed else "baseline+" + "+".join(confirmed), "groupsKept": confirmed,
        "logLoss": round(b["logloss"], 4), "brier": round(b["brier"], 4), "calibrationSlope": round(b["cal_slope"], 3), "accuracy": round(b["accuracy"], 3), "testGames": d["B"]["n_test"], "testSeason": d["B"]["season"],
        "summary": ("A rating-based view (home advantage plus a margin-aware Elo). None of the schedule, style or availability groups improved it reliably enough to be included. It cannot see injuries or lineups, and it has not been tested against sportsbook lines."
                    if not confirmed else f"A rating-based view plus {', '.join(confirmed)}. It cannot see injuries or lineups, and it has not been tested against sportsbook lines."),
        "evidence": "research/RESULTS_GAMES.md"}, indent=2) + "\n", encoding="utf-8")
    print("wrote RESULTS_GAMES.md and games.status.json; kept groups:", kept)


if __name__ == "__main__":
    main()
